const DATA_FILE = path.join(process.cwd(), 'data', 'site-data.json')
const CODE_FILE = path.join(process.cwd(), 'lib', 'site-data.ts')

export function getSiteData(): SiteData {
  try {
    if (fs.existsSync(DATA_FILE)) {
      const raw = fs.readFileSync(DATA_FILE, 'utf-8')
      const parsed = JSON.parse(raw) as SiteData
      if (!parsed.houseTour) {
        parsed.houseTour = defaultHouseTour
      }
      return parsed
    }
  } catch (err) {
    console.error('Error reading data/site-data.json:', err)
  }

  // Fallback if data file not found
  return {
    houseTour: defaultHouseTour,
  } as SiteData
}

export function saveSiteData(data: SiteData): boolean {
  try {
    // 1. Save JSON
    fs.mkdirSync(path.dirname(DATA_FILE), { recursive: true })
    fs.writeFileSync(DATA_FILE, JSON.stringify(data, null, 2), 'utf-8')

    // 2. Synchronize lib/site-data.ts
    syncToCode(data)

    return true
  } catch (err) {
    console.error('Error saving site data:', err)
    return false
  }
}

